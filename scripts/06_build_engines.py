"""Stage 5 — Calibration sets and TensorRT engines (FP32, FP16, INT8 x 3 calibration seeds).

All engines are built from the SAME frozen checkpoint (Stage 4), with the same input shape
(1x3x640x640, static), so that numerical precision is the only intended difference.

Calibration (post-training quantization of activations), per seed in config.yaml:
  * 512 images drawn uniformly at random from TRAIN with random.Random(seed) from the sorted file list
  * the list is saved (results/<tag>/calibration/calib_seed<s>.txt) together with its object-size
    statistics (needed for Table 2), and a small dataset YAML whose 'val' entry points to the list -
    Ultralytics calibrates on the 'val' split of the YAML it receives
  * preprocessing = Ultralytics' validation letterbox at 640, i.e. identical to evaluation

Each engine is built in its own folder (Ultralytics would otherwise overwrite model.engine), built
ONCE, and hashed. Existing engines are never rebuilt unless --force is given (TensorRT builds are
not bit-reproducible, so rebuilding creates a different artefact).

Usage (from the project root):
    python scripts/06_build_engines.py --tag dev  2>&1 | tee results/engines_dev_console.log
    python scripts/06_build_engines.py --tag main 2>&1 | tee results/engines_main_console.log
"""

from __future__ import annotations

import argparse
import csv
import random
import re
import shutil
import sys
import time
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.common import (  # noqa: E402
    capture_ultralytics_log, configure_ultralytics, ensure_dir, load_config, load_json, print_header,
    project_path, run_dirs, save_json, sha256_file, utc_timestamp,
)

EVIDENCE = [r"quantizing ONNX to INT8 with ModelOpt.*", r"keeping \d+ head layers out of INT8.*",
            r"building (INT8|FP16|FP32) engine.*", r"collecting INT8 calibration images.*",
            r"starting export with TensorRT .*", r".*calibration.*images.*"]


def make_calibration_set(cfg: dict, seed: int, calib_dir: Path) -> dict:
    ds_dir = project_path(cfg["paths"]["dataset_dir"])
    ccfg = cfg["calibration"]
    pool = sorted((ds_dir / "images" / ccfg["source_split"]).glob("*.jpg"))
    chosen = sorted(random.Random(seed).sample(pool, ccfg["n_images"]))
    txt = calib_dir / f"calib_seed{seed}.txt"
    txt.write_text("".join(f"{p}\n" for p in chosen), encoding="utf-8")
    names = cfg["dataset"]["class_names"]
    yaml_path = calib_dir / f"calib_seed{seed}.yaml"
    yaml_path.write_text(
        f"# calibration set, seed {seed} - generated by 06_build_engines.py\n"
        f"path: {ds_dir}\ntrain: images/train\nval: {txt}\n"
        "names:\n" + "".join(f"  {i}: {n}\n" for i, n in enumerate(names)), encoding="utf-8")

    # object-size statistics of the calibration images (labels only)
    small_u = cfg["object_size"]["small_upper_exclusive_px2"]
    large_l = cfg["object_size"]["large_lower_inclusive_px2"]
    names_set = {p.name for p in chosen}
    bins = Counter()
    with open(ds_dir / "annotations" / "objects.csv", newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["split"] == ccfg["source_split"] and r["file_name"] in names_set:
                a = float(r["area"])
                bins["small" if a < small_u else ("large" if a >= large_l else "medium")] += 1
    n = sum(bins.values())
    stats = {"seed": seed, "n_images": len(chosen), "objects": n, **{k: bins[k] for k in ("small", "medium", "large")},
             "pct_small": round(100 * bins["small"] / n, 2) if n else None,
             "list_file": str(txt), "list_sha256": sha256_file(txt), "dataset_yaml": str(yaml_path)}
    save_json(stats, calib_dir / f"calib_seed{seed}_stats.json")
    return stats


def onnx_graph_hashes(cond_dir: Path) -> dict:
    """SHA-256 of each ONNX *graph* (weights + operators), ignoring metadata such as the export date."""
    import hashlib

    import onnx

    out = {}
    for p in sorted(cond_dir.glob("*.onnx")):
        try:
            out[p.name] = hashlib.sha256(onnx.load(str(p)).graph.SerializeToString()).hexdigest()
        except Exception as e:  # noqa: BLE001
            out[p.name] = f"unreadable: {type(e).__name__}"
    return out


def evidence(log: Path) -> list[str]:
    text = log.read_text(encoding="utf-8", errors="replace") if log.exists() else ""
    return sorted({m.group(0).strip() for p in EVIDENCE for m in re.finditer(p, text)})


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--tag", default="main", choices=["main", "dev"])
    parser.add_argument("--conditions", nargs="+", default=None,
                        help="subset, e.g. fp32 int8_seed0 (default: fp32, fp16 and int8 for all seeds)")
    parser.add_argument("--force", action="store_true", help="rebuild engines that already exist")
    args = parser.parse_args()

    cfg = load_config()
    configure_ultralytics(cfg)
    dirs = run_dirs(cfg, args.tag)
    ecfg = cfg["export"]
    if not dirs["model_record"].exists():
        print(f"STOP: no frozen model for tag '{args.tag}'. Run scripts/05_train_fp32.py --tag {args.tag}")
        return 1
    model_record = load_json(dirs["model_record"])
    ckpt = Path(model_record["checkpoint"])
    if sha256_file(ckpt) != model_record["checkpoint_sha256"]:
        print("STOP: checkpoint hash differs from model_record.json - the frozen model was changed.")
        return 1

    import tensorrt as trt
    from ultralytics import YOLO, __version__ as ul_version

    seeds = cfg["calibration"]["seeds"]
    all_conditions = {"fp32": (None, None), "fp16": (16, None), **{f"int8_seed{s}": (8, s) for s in seeds}}
    wanted = args.conditions or list(all_conditions)
    unknown = set(wanted) - set(all_conditions)
    if unknown:
        print(f"STOP: unknown condition(s) {unknown}; choose from {list(all_conditions)}")
        return 1

    record = load_json(dirs["engines_record"]) if dirs["engines_record"].exists() else {"engines": {}}
    record.update({"tag": args.tag, "checkpoint": str(ckpt), "checkpoint_sha256": model_record["checkpoint_sha256"],
                   "tensorrt": trt.__version__, "ultralytics": ul_version,
                   "int8_path": "explicit Q/DQ via NVIDIA ModelOpt" if int(trt.__version__.split(".")[0]) >= 11
                   else "implicit calibration (IInt8Calibrator)"})
    print_header(f"Stage 5: engines (tag={args.tag}, TensorRT {trt.__version__}: {record['int8_path']})")

    calib_dir = ensure_dir(dirs["calibration"])
    for cond in wanted:
        quantize, seed = all_conditions[cond]
        cond_dir = ensure_dir(dirs["engines"] / cond)
        engine = cond_dir / "model.engine"
        if engine.exists() and not args.force:
            print(f"\n--> {cond}: engine exists, skipped (use --force to rebuild)")
            continue
        print(f"\n--> {cond}")
        local_pt = cond_dir / "model.pt"
        shutil.copy2(ckpt, local_pt)
        kwargs = dict(format=ecfg["format"], imgsz=ecfg["imgsz"], batch=ecfg["batch"], dynamic=ecfg["dynamic"],
                      simplify=ecfg["simplify"], device=ecfg["device"], quantize=quantize)
        calib = None
        if quantize == 8:
            calib = make_calibration_set(cfg, seed, calib_dir)
            kwargs["data"] = calib["dataset_yaml"]
            print(f"    calibration seed {seed}: {calib['n_images']} images, {calib['objects']} objects "
                  f"({calib['pct_small']}% small)")
        log = cond_dir / "export_log.txt"
        t0 = time.time()
        with capture_ultralytics_log(log):
            out = YOLO(str(local_pt)).export(**kwargs)
        if not out or not Path(out).exists():
            print(f"    FAILED - see {log}")
            return 1
        record["engines"][cond] = {
            "engine": str(out), "engine_sha256": sha256_file(out),
            "engine_size_mb": round(Path(out).stat().st_size / 2**20, 2),
            "quantize": quantize, "calibration": calib, "export_seconds": round(time.time() - t0, 1),
            "export_args": kwargs, "export_log": str(log), "log_evidence": evidence(log),
            "onnx_graph_sha256": onnx_graph_hashes(cond_dir),
            "built_utc": utc_timestamp(),
        }
        save_json(record, dirs["engines_record"])
        print(f"    OK: {out} ({record['engines'][cond]['export_seconds']} s)")
        for line in record["engines"][cond]["log_evidence"]:
            print(f"      log: {line}")

    # Informational: the FP32 ONNX graph exported from the same checkpoint should be identical for every
    # condition. (If a toolchain step rewrites model.onnx in place, e.g. for INT8, that condition differs.)
    graphs = {c: e.get("onnx_graph_sha256", {}).get("model.onnx") for c, e in record["engines"].items()}
    record["model_onnx_graph_by_condition"] = graphs
    save_json(record, dirs["engines_record"])
    print("\nmodel.onnx graph hash per condition (should match unless rewritten in place):")
    for c, h in graphs.items():
        print(f"  {c:<12s} {str(h)[:16]}")
    print(f"Record: {dirs['engines_record']}\nNext: python scripts/07_evaluate.py --tag {args.tag} --split val")
    return 0


if __name__ == "__main__":
    sys.exit(main())
